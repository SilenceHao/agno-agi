const fs = require("node:fs");
const vm = require("node:vm");
const context = {};
vm.runInNewContext(fs.readFileSync("static/vendor/marked.min.js", "utf8"), context);
vm.runInNewContext(fs.readFileSync("static/vendor/highlight.common.min.js", "utf8"), context);
const escapeHtml = (value) => value.replace(/[&<>"']/g, (character) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;", "'": "&#39;" })[character]);
const renderer = new context.marked.Renderer();
renderer.html = ({ text }) => escapeHtml(text);
renderer.image = ({ text }) => `<span class="markdown-image-placeholder">图片：${escapeHtml(text || "未命名")}</span>`;
const markdown = ["# 标题", "", "| 项目 | 状态 |", "| --- | --- |", "| 接口 | **可用** |", "", "- [x] 已完成", "", "![远程图](https://example.invalid/image.png)", "", "```javascript", "const answer = 42;", "console.log(answer);", "```", "", "<img src=x onerror=alert(1)>", ""].join("\n");
const html = context.marked.parse(markdown, { gfm: true, renderer });
const javascript = context.hljs.highlight("const answer = 42;", { language: "javascript", ignoreIllegals: true });
const python = context.hljs.highlight("def answer(): return 42", { language: "python", ignoreIllegals: true });
const json = context.hljs.highlight("{\"answer\": 42}", { language: "json", ignoreIllegals: true });
const safeCode = context.hljs.highlight("<script>alert(1)</script>", { language: "xml", ignoreIllegals: true });
if (!html.includes("<table>") || !html.includes("type=\"checkbox\"") || !html.includes("class=\"language-javascript\"")) throw new Error("GFM Markdown structures failed.");
if (!html.includes("markdown-image-placeholder") || html.includes("<img") || html.includes("<script")) throw new Error("Raw HTML or remote image handling failed.");
if (![javascript.value, python.value, json.value].some((value) => value.includes("hljs-"))) throw new Error("Syntax tokenization failed.");
if (safeCode.value.includes("<script>")) throw new Error("Highlighted code was not escaped.");
process.stdout.write("GFM, HTML/image safety, and JavaScript/Python/JSON highlighting passed\n");
